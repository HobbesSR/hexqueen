import unittest
import random
from hex_grid import HexGrid, HexCoord
from puzzle_generator import PuzzleGenerator
from solver import PuzzleSolver
from queen_placer import QueenPlacer

class TestHexGrid(unittest.TestCase):
    """Tests for the HexGrid class."""
    
    def test_grid_creation(self):
        """Test grids of different sizes are created correctly."""
        for radius in range(1, 5):
            grid = HexGrid(radius)
            # Expected number of cells in a hexagonal grid of radius r is 3*r*(r+1)+1
            expected_cells = 3 * radius * (radius + 1) + 1
            self.assertEqual(len(grid.get_all_cells()), expected_cells)
    
    def test_neighbors(self):
        """Test that neighbors are calculated correctly."""
        grid = HexGrid(3)
        center = HexCoord(0, 0, 0)
        neighbors = grid.get_neighbors(center)
        self.assertEqual(len(neighbors), 6)
        for neighbor in neighbors:
            self.assertEqual(center.distance(neighbor), 1)
        edge = HexCoord(3, -3, 0)
        edge_neighbors = grid.get_neighbors(edge)
        self.assertLess(len(edge_neighbors), 6)
    
    def test_distance(self):
        """Test distance calculation between hex coordinates."""
        grid = HexGrid(5)
        a = HexCoord(0, 0, 0)
        b = HexCoord(3, -1, -2)
        self.assertEqual(grid.get_distance(a, b), 3)
        self.assertEqual(a.distance(b), 3)

class TestPuzzleGenerator(unittest.TestCase):
    """Tests for the PuzzleGenerator class."""
    
    def setUp(self):
        self.grid = HexGrid(3)
        self.generator = PuzzleGenerator(self.grid, 4, seed=42)
    
    def test_piece_placement(self):
        """Test that pieces are placed correctly and are not overlapping."""
        success = self.generator.place_pieces()
        self.assertTrue(success)
        self.assertEqual(len(self.generator.piece_positions), 4)
        positions = list(self.generator.piece_positions.values())
        for i in range(len(positions)):
            for j in range(i + 1, len(positions)):
                self.assertGreater(positions[i].distance(positions[j]), 0)
    
    def test_region_growth(self):
        """Test that regions grow to cover the entire grid and are contiguous."""
        self.generator.place_pieces()
        success = self.generator.grow_regions()
        self.assertTrue(success)
        self.assertEqual(len(self.generator.cell_regions), len(self.grid.get_all_cells()))
        self.assertTrue(self.generator.are_all_regions_contiguous())
    
    def test_puzzle_generation(self):
        """Test complete puzzle generation including puzzle properties."""
        generator = PuzzleGenerator(self.grid, 3, seed=42)
        success = generator.generate_puzzle()
        self.assertTrue(success)
        state = generator.get_puzzle_state()
        self.assertEqual(state['grid_radius'], self.grid.radius)
        self.assertEqual(state['num_pieces'], 3)
        self.assertEqual(len(state['piece_positions']), 3)
        self.assertEqual(len(state['cell_regions']), len(self.grid.get_all_cells()))

class TestPuzzleSolver(unittest.TestCase):
    """Tests for the PuzzleSolver class."""
    
    def test_naked_singles(self):
        """Test the naked singles technique improves puzzle progress."""
        grid = HexGrid(2)
        solver = PuzzleSolver(grid, 3)
        piece_positions = {
            0: HexCoord(0, 0, 0),
            1: HexCoord(2, -1, -1),
            2: HexCoord(-2, 1, 1)
        }
        solver.initialize_from_clues(piece_positions)
        progress = solver.apply_naked_singles_technique()
        self.assertTrue(progress)
    
    def test_solver_with_generated_puzzle(self):
        """Test the solver with a puzzle generated by the PuzzleGenerator."""
        grid = HexGrid(2)
        generator = PuzzleGenerator(grid, 3, seed=42)
        success = generator.generate_puzzle()
        self.assertTrue(success)
        solver = PuzzleSolver(grid, 3)
        solver.initialize_from_clues(generator.piece_positions)
        solved = solver.solve()
        self.assertTrue(solved)
        solution = solver.get_solution()
        self.assertEqual(len(solution), len(grid.get_all_cells()))
    
    def test_solution_uniqueness(self):
        """Test that generated puzzles have unique solutions."""
        grid = HexGrid(2)
        generator = PuzzleGenerator(grid, 3, seed=42)
        success = generator.generate_puzzle()
        self.assertTrue(success)
        solver = PuzzleSolver(grid, 3)
        solver.initialize_from_clues(generator.piece_positions)
        solution_count = solver.count_solutions(2)
        self.assertEqual(solution_count, 1)

class TestQueenPlacer(unittest.TestCase):
    """Tests for the QueenPlacer class."""
    
    def setUp(self):
        self.grid = HexGrid(3)
        self.placer = QueenPlacer(self.grid, 3, seed=42)
    
    def test_random_queen_placement(self):
        """Test queen placement using the random strategy."""
        success = self.placer.place_queens_random()
        self.assertTrue(success)
        positions = self.placer.get_queen_positions()
        self.assertEqual(len(positions), 3)
        # Ensure no queen is attacked by another queen
        for qid, pos in positions.items():
            self.assertFalse(self.placer.is_cell_attacked(pos, exclude_queen=qid))
    
    def test_backtracking_queen_placement(self):
        """Test queen placement using the backtracking strategy."""
        success = self.placer.place_queens_backtracking()
        self.assertTrue(success)
        positions = self.placer.get_queen_positions()
        self.assertEqual(len(positions), 3)
        for qid, pos in positions.items():
            self.assertFalse(self.placer.is_cell_attacked(pos, exclude_queen=qid))
    
    def test_combined_queen_placement(self):
        """Test queen placement using the combined strategy (random then backtracking)."""
        success = self.placer.place_queens()
        self.assertTrue(success)
        positions = self.placer.get_queen_positions()
        self.assertEqual(len(positions), 3)
        for qid, pos in positions.items():
            self.assertFalse(self.placer.is_cell_attacked(pos, exclude_queen=qid))

